import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

// The VPS and standalone package have no node_modules. Ship the exact editor
// evaluator as ordinary ESM; CI rejects a stale generated copy.
export async function generateAiRuntime({check=false}={}){
 const root=fileURLToPath(new URL('..',import.meta.url));
 const result=await build({stdin:{contents:"export {validateAiPlan,simulateAiPlan} from './src/editor/ai';export {normalizeProject,totalLength} from './src/editor/model';",resolveDir:root,loader:'ts'},bundle:true,write:false,format:'esm',platform:'neutral',target:'es2022',legalComments:'none'});
 const content='// Generated by tools/generate-ai-runtime.mjs. Edit src/editor/ai.ts or model.ts, then regenerate.\n'+result.outputFiles[0].text;
 const output=new URL('../shared/editor-ai-runtime.mjs',import.meta.url);
 if(check){if(await readFile(output,'utf8')!==content)throw Error('AI evaluator is stale. Run node tools/generate-ai-runtime.mjs.');}
 else await writeFile(output,content);
}
if(process.argv[1]===fileURLToPath(import.meta.url))await generateAiRuntime({check:process.argv.includes('--check')});
